#!/usr/bin/env python3
"""
Converts Lucide SVG icons (https://lucide.dev/icons/) into a Kotlin file with
Compose ImageVector definitions, so the app needs no icon dependency.

Usage:
    python3 tools/lucide_to_kotlin.py <dir-with-svgs> <output.kt>

Every SVG primitive (path, circle, rect, line, polyline, polygon, ellipse) is
converted into SVG path data and rendered as a 2px round-capped stroke, which
is exactly how Lucide draws its icons.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

NS = "{http://www.w3.org/2000/svg}"


def f(v: str) -> str:
    x = float(v)
    s = ("%.4f" % x).rstrip("0").rstrip(".")
    return s if s else "0"


NUM = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")


def normalize_path(d: str) -> str:
    """Rewrites SVG path data with every number separated by a space.

    SVG allows compact forms such as "a2 2 0 01-3-4" where the two arc flags are
    glued together; Compose's path parser is not guaranteed to accept that, so
    arc flags are tokenised one character at a time and everything is re-joined
    with explicit separators.
    """
    out = []
    i = 0
    cmd = ""
    arg_index = 0
    while i < len(d):
        c = d[i]
        if c.isalpha():
            cmd = c
            arg_index = 0
            out.append(c)
            i += 1
            continue
        if c in " ,\t\n\r":
            i += 1
            continue
        if cmd in "aA" and arg_index % 7 in (3, 4):
            # Arc flags are exactly one character (0 or 1).
            out.append(c)
            arg_index += 1
            i += 1
            continue
        m = NUM.match(d, i)
        if not m:
            raise ValueError(f"cannot parse path data near: {d[i:i+20]!r}")
        out.append(m.group(0))
        arg_index += 1
        i = m.end()
    return " ".join(out)


def element_to_path(el) -> str | None:
    tag = el.tag.replace(NS, "")
    a = el.attrib
    if tag == "path":
        return normalize_path(a["d"].strip())
    if tag == "circle":
        cx, cy, r = float(a["cx"]), float(a["cy"]), float(a["r"])
        return (f"M{f(str(cx - r))} {f(str(cy))}"
                f"a{f(str(r))} {f(str(r))} 0 1 0 {f(str(2 * r))} 0"
                f"a{f(str(r))} {f(str(r))} 0 1 0 {f(str(-2 * r))} 0")
    if tag == "ellipse":
        cx, cy, rx, ry = (float(a[k]) for k in ("cx", "cy", "rx", "ry"))
        return (f"M{f(str(cx - rx))} {f(str(cy))}"
                f"a{f(str(rx))} {f(str(ry))} 0 1 0 {f(str(2 * rx))} 0"
                f"a{f(str(rx))} {f(str(ry))} 0 1 0 {f(str(-2 * rx))} 0")
    if tag == "rect":
        x, y = float(a.get("x", 0)), float(a.get("y", 0))
        w, h = float(a["width"]), float(a["height"])
        rx = float(a.get("rx", a.get("ry", 0)))
        ry = float(a.get("ry", rx))
        if rx == 0 and ry == 0:
            return f"M{f(str(x))} {f(str(y))}h{f(str(w))}v{f(str(h))}h{f(str(-w))}z"
        return (f"M{f(str(x + rx))} {f(str(y))}"
                f"h{f(str(w - 2 * rx))}"
                f"a{f(str(rx))} {f(str(ry))} 0 0 1 {f(str(rx))} {f(str(ry))}"
                f"v{f(str(h - 2 * ry))}"
                f"a{f(str(rx))} {f(str(ry))} 0 0 1 {f(str(-rx))} {f(str(ry))}"
                f"h{f(str(-(w - 2 * rx)))}"
                f"a{f(str(rx))} {f(str(ry))} 0 0 1 {f(str(-rx))} {f(str(-ry))}"
                f"v{f(str(-(h - 2 * ry)))}"
                f"a{f(str(rx))} {f(str(ry))} 0 0 1 {f(str(rx))} {f(str(-ry))}z")
    if tag == "line":
        return f"M{f(a['x1'])} {f(a['y1'])}L{f(a['x2'])} {f(a['y2'])}"
    if tag in ("polyline", "polygon"):
        nums = [f(n) for n in re.split(r"[\s,]+", a["points"].strip()) if n]
        pts = list(zip(nums[0::2], nums[1::2]))
        d = "M" + " ".join(f"{x} {y}" for x, y in pts)
        d = d.replace("M", "M", 1)
        d = "M" + f"{pts[0][0]} {pts[0][1]}" + "".join(f"L{x} {y}" for x, y in pts[1:])
        return d + ("z" if tag == "polygon" else "")
    return None


def kotlin_name(stem: str) -> str:
    return "".join(p.capitalize() for p in stem.split("-"))


def main() -> None:
    src = Path(sys.argv[1])
    out = Path(sys.argv[2])
    entries = []
    for svg in sorted(src.glob("*.svg")):
        root = ET.parse(svg).getroot()
        paths = []
        for el in root.iter():
            d = element_to_path(el)
            if d:
                paths.append(d)
        entries.append((kotlin_name(svg.stem), svg.stem, paths))

    lines = [
        "// GENERATED by tools/lucide_to_kotlin.py from Lucide icons (ISC license,",
        "// https://lucide.dev). Do not edit by hand; re-run the tool instead.",
        "package com.vislupus.waifuverse.ui.icons",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.graphics.SolidColor",
        "import androidx.compose.ui.graphics.StrokeCap",
        "import androidx.compose.ui.graphics.StrokeJoin",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.addPathNodes",
        "import androidx.compose.ui.unit.dp",
        "",
        "/** Lucide icons as Compose ImageVectors (24x24, 2px round stroke). Tint them with Icon(tint = ...). */",
        "object Lucide {",
    ]
    for name, stem, paths in entries:
        joined = ",\n        ".join('"' + p.replace('"', '\\"') + '"' for p in paths)
        lines.append(f"    val {name}: ImageVector by lazy {{")
        lines.append(f"        lucide(\"{stem}\",")
        lines.append(f"        {joined})")
        lines.append("    }")
        lines.append("")
    lines += [
        "    private fun lucide(name: String, vararg pathData: String): ImageVector {",
        "        val builder = ImageVector.Builder(",
        "            name = \"lucide-$name\",",
        "            defaultWidth = 24.dp,",
        "            defaultHeight = 24.dp,",
        "            viewportWidth = 24f,",
        "            viewportHeight = 24f,",
        "        )",
        "        for (d in pathData) {",
        "            builder.addPath(",
        "                pathData = addPathNodes(d),",
        "                fill = null,",
        "                stroke = SolidColor(Color.Black),",
        "                strokeLineWidth = 2f,",
        "                strokeLineCap = StrokeCap.Round,",
        "                strokeLineJoin = StrokeJoin.Round,",
        "            )",
        "        }",
        "        return builder.build()",
        "    }",
        "}",
        "",
    ]
    out.write_text("\n".join(lines))
    print(f"wrote {len(entries)} icons -> {out}")


if __name__ == "__main__":
    main()
