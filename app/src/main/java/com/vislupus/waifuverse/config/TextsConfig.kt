/**
 * =====================================================================
 *  TEXTS CONFIG — every string shown in the interface, per language.
 * =====================================================================
 *
 * The interface language is chosen in Settings. To add a language: add a
 * value to [Language] and a new [Texts] instance below, then register it in
 * [TextsConfig.forLanguage].
 */
object TextsConfig {
    fun forLanguage(language: Language): Texts = when (language) {
        Language.EN -> EnglishTexts
        Language.BG -> BulgarianTexts
    }
}

